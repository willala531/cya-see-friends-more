// ─── Activity data library ────────────────────────────────────────────────────
// Single source of truth for all activity data used by the suggestion engine
// and the interest-selection UI. Never hardcode activity strings elsewhere.

export interface Activity {
  id: string;
  name: string;
  category: string;
  minDuration: number;       // minutes, excluding transport buffer
  maxDuration: number;       // minutes, excluding transport buffer
  transportBuffer: number;   // minutes per end (50 total)
  timeWindow: {
    start: number;           // fractional hour, e.g. 17.5 = 5:30pm
    end: number;             // fractional hour, e.g. 20.5 = 8:30pm
  };
  seasonalRestriction: "april-october" | "year-round";
  indoorOutdoor: "indoor" | "outdoor" | "both";
  /** When set, the free slot must be at least this long (overrides minDuration+buffer). */
  minFreeTimeMinutes?: number;
}

